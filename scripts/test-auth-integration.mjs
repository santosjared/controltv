import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';
const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const cookieValues = new Map();
let fetchImpl;
const calls = [];
const runtime = { API_BASE_URL: 'http://backend.test', NODE_ENV: 'test' };
function response(body, options = {}) {
  const result = new Response(JSON.stringify(body), options);
  const values = new Map();
  result.cookies = { set(name, value, options) { values.set(name, { value, ...options }); }, get(name) { return values.get(name); } };
  return result;
}
const store = { get: (key) => cookieValues.has(key) ? {value: cookieValues.get(key)} : undefined, set: (key, value) => cookieValues.set(key, value) };
const modules = new Map();
function load(file) {
  if (modules.has(file)) return modules.get(file);
  const ctx = { exports: {}, require(name) {
    if (name === 'server-only') return {};
    if (name === 'next/headers') return {cookies: async () => store};
    if (name === 'next/server') return {NextResponse: {json: response}};
    if (name.endsWith('auth-config')) return load('src/features/auth/auth-config.ts');
    if (name.endsWith('refresh-session')) return load('src/features/auth/refresh-session.ts');
    throw new Error('Unexpected import: ' + name);
  }, fetch: async (...args) => { calls.push(args); return fetchImpl(...args); }, Buffer, Response, Request, Headers, AbortSignal, URL, setTimeout, clearTimeout, process: {env: runtime} };
  vm.runInNewContext(ts.transpileModule(fs.readFileSync(path.join(root, file), 'utf8'), {compilerOptions: {module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022}}).outputText, ctx);
  modules.set(file, ctx.exports);
  return ctx.exports;
}
const config = load('src/features/auth/auth-config.ts');
const current = {id: 'user', name: 'Usuario', username: 'usuario', roleId: 'role', roleName: 'Operador', persistent: true, permissions: ['roles.manage']};
