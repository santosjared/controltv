const access = 'header.' + Buffer.from(JSON.stringify({exp: Date.now() / 1000 + 600})).toString('base64url') + '.signature';
cookieValues.set(config.SESSION_COOKIE, config.encodeSessionUser(current));
cookieValues.set(config.ACCESS_TOKEN_COOKIE, access);
cookieValues.set(config.REFRESH_TOKEN_COOKIE, 'test-refresh');
